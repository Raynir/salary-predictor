"""Refresh CBR USD/RUB rates and regenerate src/data.js, the data predictor.html loads.

Python 3.8+ standard library only. Usage:

    python update_data.py              # fetch new CBR rates, update CSV, regenerate src/data.js
    python update_data.py --no-fetch   # only regenerate (e.g. after editing company_rates.csv)
    python update_data.py --month 2026-10 --expected 85.5

src/data.js is always built from data/ only. The prediction printed at the end uses private/company_rates.csv
(gitignored) when it exists, so real company rates can stay out of the repository; make_zip.py embeds them in the
archive it builds.
"""

import argparse
import csv
import datetime as dt
import io
import json
import statistics
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CBR_CSV = ROOT / "data" / "cbr_usd.csv"
COMPANY_CSV = ROOT / "data" / "company_rates.csv"
PRIVATE_COMPANY_CSV = ROOT / "private" / "company_rates.csv"
HOLIDAYS_CSV = ROOT / "data" / "holidays.csv"
DATA_JS = ROOT / "src" / "data.js"

CBR_URL = ("https://www.cbr.ru/scripts/XML_dynamic.asp"
           "?date_req1={d1}&date_req2={d2}&VAL_NM_RQ=R01235")  # R01235 = USD
CURRENCY_NAME = "Доллар США"


# ---------- parsing ----------

def parse_date(s):
    s = s.strip()
    if "/" in s:  # M/D/YYYY
        m, d, y = s.split("/")
        return dt.date(int(y), int(m), int(d))
    if "." in s:  # DD.MM.YYYY
        d, m, y = s.split(".")
        return dt.date(int(y), int(m), int(d))
    return dt.date.fromisoformat(s)


def parse_num(s):
    return float(s.strip().replace(",", "."))


def read_text(path):
    """UTF-8, or Windows-1251 as saved by Russian-locale Excel."""
    raw = Path(path).read_bytes()
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        text = raw.decode("cp1251")
    return text.replace("\r\n", "\n")


def read_rates(path):
    """Return {date: rate per 1 unit} from a nominal,date,curs[,cdx] CSV (comma or semicolon)."""
    text = read_text(path)
    first = text.split("\n", 1)[0]
    delimiter = ";" if ";" in first else "\t" if "\t" in first else ","
    rates = {}
    for row in list(csv.reader(io.StringIO(text), delimiter=delimiter))[1:]:
        if len(row) < 3 or not row[1].strip():
            continue
        nominal = parse_num(row[0]) or 1.0
        rates[parse_date(row[1])] = parse_num(row[2]) / nominal
    return rates


def write_cbr_csv(path, rates):
    out = io.StringIO()
    out.write("nominal,data,curs,cdx\n")
    for d in sorted(rates, reverse=True):
        out.write(f"1,{d.month}/{d.day}/{d.year},{rates[d]:.4f},{CURRENCY_NAME}\n")
    write_lf(path, out.getvalue())


def write_lf(path, text):
    # Path.write_text would turn \n into \r\n on Windows
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


# ---------- fetching ----------

def fetch_cbr(start, end):
    url = CBR_URL.format(d1=start.strftime("%d/%m/%Y"), d2=end.strftime("%d/%m/%Y"))
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 SalaryPredictor"})
    with urllib.request.urlopen(req, timeout=20) as resp:
        root = ET.fromstring(resp.read())
    rates = {}
    for rec in root.iter("Record"):
        nominal = parse_num(rec.findtext("Nominal", "1"))
        rates[parse_date(rec.get("Date"))] = parse_num(rec.findtext("Value")) / nominal
    return rates


# ---------- data.js ----------

def data_js_text(company_csv=COMPANY_CSV):
    payload = {
        "cbr": read_text(CBR_CSV),
        "company": read_text(company_csv),
        "holidays": read_text(HOLIDAYS_CSV) if HOLIDAYS_CSV.exists() else "",
        "builtAt": dt.date.today().isoformat(),
    }
    return ("// Generated by update_data.py from data/*.csv. Do not edit by hand.\n"
            "const EMBEDDED = " + json.dumps(payload, ensure_ascii=False) + ";\n")


def write_data_js(path):
    write_lf(path, data_js_text())


# ---------- model (mirrors src/js/model.js) ----------

def month_end(y, m):
    return dt.date(y + (m == 12), m % 12 + 1, 1) - dt.timedelta(days=1)


def by_month(rates):
    months = {}
    for d in sorted(rates):
        months.setdefault((d.year, d.month), []).append(rates[d])
    return months


def percentile(values, p):
    v = sorted(values)
    pos = (len(v) - 1) * p
    lo = int(pos)
    hi = min(lo + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (pos - lo)


def history_ratios(cbr, company, before, n_months):
    """company/CBR-average ratios for complete months strictly before `before`."""
    months = by_month(cbr)
    first = min(cbr)
    ratios = []
    for ym in sorted(company):
        if ym >= before or ym not in months:
            continue
        if ym == (first.year, first.month) or len(months[ym]) < 5:
            continue  # the CBR file may start mid-month
        ratios.append(company[ym] / statistics.mean(months[ym]))
    return ratios[-n_months:] if n_months else ratios


def remaining_publication_days(after, y, m):
    """CBR rates are dated Tuesday through Saturday."""
    d, end, n = after + dt.timedelta(days=1), month_end(y, m), 0
    while d <= end:
        n += d.weekday() in (1, 2, 3, 4, 5)
        d += dt.timedelta(days=1)
    return n


def predict(cbr, company, ym, expected=None, n_months=12):
    y, m = ym
    known = [cbr[d] for d in sorted(cbr) if (d.year, d.month) == ym]
    known_dates = [d for d in cbr if (d.year, d.month) == ym]
    last = max(known_dates) if known_dates else dt.date(y, m, 1) - dt.timedelta(days=1)
    r = remaining_publication_days(last, y, m)
    if expected is None:
        expected = cbr[max(cbr)]
    n = len(known)
    avg = (sum(known) + r * expected) / (n + r) if n + r else expected
    ratios = history_ratios(cbr, company, ym, n_months)
    if not ratios:  # like model.js: no company rates, no spread
        return {"known": n, "remaining": r, "expected": expected, "cbr_avg": avg, "k": None}
    k = statistics.median(ratios)
    return {
        "known": n, "remaining": r, "expected": expected, "cbr_avg": avg,
        "k": k, "prediction": k * avg,
        "low": percentile(ratios, 0.1) * avg, "high": percentile(ratios, 0.9) * avg,
        "months_used": len(ratios),
    }


# ---------- main ----------

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-fetch", action="store_true", help="skip downloading new CBR rates")
    ap.add_argument("--month", help="month to predict, YYYY-MM (default: current month)")
    ap.add_argument("--expected", type=float, help="expected USD rate for the rest of the month")
    ap.add_argument("--months", type=int, default=12, help="history months used for the spread (0 = all)")
    args = ap.parse_args()

    cbr = read_rates(CBR_CSV)
    today = dt.date.today()

    if not args.no_fetch:
        start = max(cbr) + dt.timedelta(days=1)
        end = today + dt.timedelta(days=1)  # CBR sets tomorrow's rate in the afternoon
        if start > end:
            print("CBR data already up to date.")
        else:
            try:
                new = fetch_cbr(start, end)
                added = {d: v for d, v in new.items() if d not in cbr}
                if added:
                    cbr.update(added)
                    write_cbr_csv(CBR_CSV, cbr)
                print(f"Fetched {len(added)} new CBR rate(s) from cbr.ru.")
            except Exception as e:  # network or parse errors shouldn't block re-embedding
                print(f"warning: could not fetch from cbr.ru ({e}); using local data.")

    write_data_js(DATA_JS)
    last = max(cbr)
    print(f"Wrote src/data.js. Latest CBR rate: {last:%d.%m.%Y} = {cbr[last]:.4f}")

    company_csv = PRIVATE_COMPANY_CSV if PRIVATE_COMPANY_CSV.exists() else COMPANY_CSV
    company = {(d.year, d.month): v for d, v in read_rates(company_csv).items()}
    if args.month:
        y, m = map(int, args.month.split("-"))
    else:
        y, m = today.year, today.month
    p = predict(cbr, company, (y, m), args.expected, args.months)
    source = company_csv.relative_to(ROOT).as_posix()
    if p["k"] is None:
        print(f"\nNo company rates in {source}, so no prediction. "
              f"CBR average for {m:02d}.{y}: {p['cbr_avg']:.4f}")
        return
    print(f"\nCompany rates from {source}.")
    print(f"\nPrediction for {m:02d}.{y}: {p['prediction']:.2f} RUB "
          f"(range {p['low']:.2f}-{p['high']:.2f})")
    print(f"  CBR rates known: {p['known']}, remaining days: {p['remaining']} at {p['expected']:.4f}")
    print(f"  CBR month average: {p['cbr_avg']:.4f}, spread k = {p['k']:.4f} "
          f"(median of {p['months_used']} months)")
    if (y, m) in company:
        print(f"  Actual company rate: {company[(y, m)]:.2f}")


if __name__ == "__main__":
    main()
